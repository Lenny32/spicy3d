// Codegen of the typed server API (packages/cloud/src/api/schema.generated.ts) from the OpenAPI
// document the server (SpicySrv) publishes. The spec is committed (packages/cloud/openapi.json) so
// the web build never needs the server or the network.
//
//   npm run cloud:api                          regenerate the types from the committed spec
//   npm run cloud:api -- <path-or-url>         replace the committed spec (e.g. http://host/openapi/v1.json), then regenerate
//   npm run cloud:api:check                    exit 1 when the committed types are stale (CI)
//
// `packages/cloud/test/generatedApi.test.ts` runs the check with the suite as well.

import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString, NULL, NUMBER, tsUnion } from "openapi-typescript";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = resolve(root, "packages/cloud/openapi.json");
const defaultOutPath = resolve(root, "packages/cloud/src/api/schema.generated.ts");

const HEADER = `// Part of the Spicy3D Project, derived from Chili3D, under the AGPL-3.0 License.
// See LICENSE file in the project root for full license information.

// GENERATED by scripts/generate-cloud-api.mjs from packages/cloud/openapi.json — do not edit.
// Regenerate with \`npm run cloud:api\` (or \`npm run cloud:api -- <path-or-url>\` for a newer spec).

`;

/**
 * Raw bytes (`format: binary`, e.g. a blob upload) are a `Blob` in the browser, not a `string`.
 *
 * ASP.NET Core types every int as `["integer", "string"]` with a digits pattern, because its JSON
 * options accept numbers written as strings (SpicySrv#8). The server always writes JSON numbers, so
 * the client types them as `number` (keeping `null` where the schema allows it).
 */
function transform(schema) {
    if (schema.type === "string" && schema.format === "binary") {
        return ts.factory.createTypeReferenceNode("Blob");
    }
    const types = Array.isArray(schema.type) ? schema.type : undefined;
    if (!types?.includes("integer") || !types.includes("string")) return undefined;
    const rest = types.filter((t) => t !== "integer" && t !== "string");
    if (rest.some((t) => t !== "null")) return undefined;
    return rest.length > 0 ? tsUnion([NUMBER, NULL]) : NUMBER;
}

async function readSpec(source) {
    const text = /^https?:\/\//i.test(source)
        ? await fetch(source).then((response) => {
              if (!response.ok) throw new Error(`GET ${source} answered ${response.status}`);
              return response.text();
          })
        : readFileSync(resolve(process.cwd(), source), "utf8");
    const spec = JSON.parse(text);
    if (typeof spec.openapi !== "string" || typeof spec.paths !== "object") {
        throw new Error(`${source} is not an OpenAPI document`);
    }
    return spec;
}

function biome(args, input) {
    const require = createRequire(import.meta.url);
    const launcher = resolve(dirname(require.resolve("@biomejs/biome/package.json")), "bin/biome");
    // Maintainer-run codegen: runs the repo's own Biome with repo-authored arguments, no shell.
    // nosemgrep: javascript.lang.security.detect-child-process.detect-child-process
    const result = spawnSync(process.execPath, [launcher, ...args], { cwd: root, input, encoding: "utf8" });
    if (result.error) throw result.error;
    if (result.status !== 0) throw new Error(`biome ${args[0]} failed: ${result.stderr}`);
    return result.stdout;
}

/** The generated module for the committed spec, formatted the way `npm run check` leaves it. */
export async function generate() {
    const spec = JSON.parse(readFileSync(specPath, "utf8"));
    const ast = await openapiTS(spec, { transform, alphabetize: true, silent: true });
    return biome(
        ["format", `--stdin-file-path=${relative(root, defaultOutPath)}`],
        HEADER + astToString(ast),
    );
}

async function main() {
    const args = process.argv.slice(2);
    const check = args.includes("--check");
    // `--out <file>`: the generated file to write or check (tests check a stale copy).
    const outIndex = args.indexOf("--out");
    const outPath = outIndex >= 0 ? resolve(process.cwd(), args[outIndex + 1]) : defaultOutPath;
    const source = args.find((arg, i) => !arg.startsWith("--") && (outIndex < 0 || i !== outIndex + 1));

    if (check) {
        const current = readFileSync(outPath, "utf8");
        if ((await generate()) !== current) {
            console.error(
                `${relative(root, outPath)} is stale: it no longer matches packages/cloud/openapi.json. ` +
                    "Run `npm run cloud:api` and commit the result.",
            );
            process.exit(1);
        }
        console.log(`${relative(root, outPath)} is up to date.`);
        return;
    }

    if (source) {
        const spec = await readSpec(source);
        writeFileSync(specPath, `${JSON.stringify(spec, null, 4)}\n`);
        biome(["format", "--write", specPath]);
        console.log(`Updated ${relative(root, specPath)} from ${source} (API ${spec.info?.version ?? "?"}).`);
    }
    writeFileSync(outPath, await generate());
    console.log(`Generated ${relative(root, outPath)}.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main().catch((error) => {
        console.error(error instanceof Error ? error.message : error);
        process.exit(1);
    });
}
